// Sasta Milaga — WooCommerce-only origin bridge.
// Public GitHub Pages content is never served by this Worker.
// Requests keep the public Host/same-site cookies and are routed internally to
// the retained Namecheap IP through Cloudflare's same-zone resolveOverride.
const PUBLIC_HOST = 'sastamilaga.com';
const NAMECHEAP_ORIGIN = 'origin.sastamilaga.com';
const PRIVATE_PATH = /^\/(?:cart|checkout|my-account|order-pay|order-received|wp-admin|wp-json|wp-content|wp-includes|wp-login\.php|wc-api|xmlrpc\.php)(?:\/|$|[?#])/i;
const DOC_PATH = /^\/(?:cart|checkout|my-account|order-pay|order-received)(?:\/|$)/i;
const ALLOWED = new Set(['GET','HEAD','POST','PUT','PATCH','DELETE','OPTIONS']);
function unavailable(request,kind) {
  const pathname = new URL(request.url).pathname;
  const api = pathname.startsWith('/wp-json') || pathname.startsWith('/wc-api') || /application\/json/i.test(request.headers.get('accept')||'');
  const status = 503;
  const headers = {'cache-control':'private, no-store, max-age=0','cloudflare-cdn-cache-control':'no-store','retry-after':'60','x-robots-tag':'noindex','x-sasta-commerce-origin':'unavailable'};
  if(api) return new Response(request.method==='HEAD'?null:JSON.stringify({error:'WooCommerce origin temporarily unavailable',code:kind}),{status,headers:{...headers,'content-type':'application/json; charset=utf-8'}});
  const body = '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex"><title>Secure checkout temporarily unavailable</title></head><body style="font:16px/1.5 system-ui;max-width:650px;margin:10vh auto;padding:0 24px"><h1>Sasta Milaga</h1><h2>Secure checkout is temporarily unavailable</h2><p>Your payment and order have not been submitted through this page. Please try again once the checkout service has recovered.</p><a href="/">Continue browsing</a></body></html>';
  return new Response(request.method==='HEAD'?null:body,{status,headers:{...headers,'content-type':'text/html; charset=utf-8'}});
}
export default {
  async fetch(request) {
    const incoming = new URL(request.url);
    if(!ALLOWED.has(request.method)) return new Response('Method Not Allowed',{status:405,headers:{allow:[...ALLOWED].join(', ')}});
    // This is a route handler, not a general open proxy. Allow only WooCommerce paths.
    if(!PRIVATE_PATH.test(incoming.pathname)) return new Response('Not found',{status:404,headers:{'cache-control':'no-store'}});
    const target = new URL(request.url);
    target.protocol = 'https:';
    target.hostname = PUBLIC_HOST;
    target.port = '';
    const headers = new Headers(request.headers);
    // Host is generated by fetch() from target URL. Do not forward untrusted spoofed headers.
    for(const name of ['x-forwarded-host','x-original-host','x-sasta-commerce-origin']) headers.delete(name);
    let response;
    try {
      const upstream = new Request(target.toString(),request);
      response = await fetch(upstream,{
        redirect:'manual',
        cf:{resolveOverride:NAMECHEAP_ORIGIN,cacheEverything:false,cacheTtlByStatus:{'100-599':-1}},
        signal:AbortSignal.timeout(16000)
      });
    } catch(e) {
      console.log(JSON.stringify({event:'woo_origin_network_failure',path:incoming.pathname,kind:String(e?.name||'error')}));
      return unavailable(request,'upstream_network');
    }
    if(response.status >= 500) {
      await response.body?.cancel().catch(()=>{});
      return unavailable(request,'upstream_'+response.status);
    }
    const outgoing = new Response(request.method==='HEAD'?null:response.body,response);
    outgoing.headers.set('cache-control','private, no-store, max-age=0');
    outgoing.headers.set('cloudflare-cdn-cache-control','no-store');
    outgoing.headers.set('x-sasta-commerce-origin','namecheap');
    // Don't turn a legitimate WordPress authentication or cart redirect into a cross-domain redirect.
    const location = outgoing.headers.get('location');
    if(location) {
      const to = new URL(location, PUBLIC_HOST==='sastamilaga.com'?'https://sastamilaga.com':'https://'+PUBLIC_HOST);
      if(to.hostname===NAMECHEAP_ORIGIN) {
        to.hostname = PUBLIC_HOST;
        outgoing.headers.set('location',to.toString());
      }
    }
    return outgoing;
  }
};